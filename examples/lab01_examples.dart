// 2. ВВОД ДАННЫХ И ПРЕВРАЩЕНИЕ СТРОКИ В ЧИСЛО
// ---------------------------------------------------------------------------
// @INPUT@
void demoInput() {
  print('\n=== 2. Ввод и приведение типов ===\n');

  // В настоящей программе строку берут так:
  //     stdout.write('Название: ');
  //     final String? answer = stdin.readLineSync();
  //
  // Обратите внимание на вопросительный знак: readLineSync() возвращает
  // String?, то есть значение МОЖЕТ отсутствовать. Компилятор не позволит
  // использовать его там, где ожидается String.
  //
  // Здесь, чтобы файл не требовал ввода, подставлены готовые значения.
  // Список изображает две ситуации: пользователь ввёл строку и закрыл ввод
  final List<String?> simulated = <String?>['Интерстеллар', null];
  final String? typed = simulated[0];
  final String? nothing = simulated[1];

  // ?? подставляет запасное значение, если слева null
  print('Введено: ${typed ?? 'ничего не введено'}');
  print('Введено: ${nothing ?? 'ничего не введено'}');

  // Строку в число превращают двумя способами.
  // parse бросает исключение при неверном вводе — программа упадёт.
  print('int.parse("2014")   = ${int.parse('2014')}');

  // tryParse возвращает null — именно это нужно для ввода пользователя.
  print('int.tryParse("2014") = ${int.tryParse('2014')}');
  print('int.tryParse("абв")  = ${int.tryParse('абв')}');

  // Приём для работы: разобрать и сразу подставить запасное значение
  final int duration = int.tryParse('абв') ?? 0;
  print('Длительность после подстановки: $duration');

  // Для дробных — double.tryParse. Пользователи часто вводят запятую:
  final double rating = double.tryParse('8,6'.replaceAll(',', '.')) ?? 0;
  print('Оценка: $rating');
}
// @INPUT_END@

