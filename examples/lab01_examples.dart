// 6. NULL, FINAL/CONST, КАСКАД, «ЛЕНИВЫЕ» ОПЕРАТОРЫ
// ---------------------------------------------------------------------------
// @NULLOPS@
void demoNullAndOperators() {
  print('\n=== 6. Операторы null, final/const, каскад ===\n');

  final Map<String, String> info = <String, String>{'title': 'Интерстеллар'};
  String? slogan = info['slogan']; // ключа нет, значит null

  print('?.  → ${slogan?.length} — метод не вызывался, упасть не может');
  print('??  → ${slogan ?? 'слогана нет'} — подставили запасное значение');
  slogan ??= 'Мы найдём выход'; // присвоить, только если было null
  print('??= → $slogan');

  // «Ленивое» вычисление: второй операнд вычисляется не всегда.
  // Список пуст, и деление на его длину было бы делением на ноль —
  // но до второго операнда выполнение просто не доходит.
  final List<int> empty = <int>[];
  final bool andResult = empty.isNotEmpty && 100 ~/ empty.length > 1;
  final bool orResult = empty.isEmpty || 100 ~/ empty.length > 1;
  print('&& → $andResult, || → $orResult — ошибки не произошло');

  // final: присвоить заново нельзя, но содержимое менять можно
  final List<String> actors = <String>['МакКонахи'];
  actors.add('Хэтэуэй');
  print('final-список: $actors');

  // const: объект заморожен целиком, содержимое менять нельзя
  const List<String> awards = <String>['Оскар за спецэффекты'];
  print('const-список: $awards');

  // Каскад .. — несколько действий над одним объектом подряд
  final StringBuffer description = StringBuffer()
    ..write('Интерстеллар')
    ..write(', 2014')
    ..writeln('. Режиссёр Нолан.');
  print('Каскад собрал: $description');
}

// @NULLOPS_END@
