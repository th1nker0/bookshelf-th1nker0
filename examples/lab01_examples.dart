// @NUMBERS@
void demoNumbers() {
  print('\n=== 3. Числа и операторы ===\n');

  final int minutes = 169; // длительность «Интерстеллара»

  // ВАЖНО: в Dart / всегда даёт double, даже если оба операнда целые
  print('169 / 60  = ${minutes / 60}   — тип double');
  print('169 ~/ 60 = ${minutes ~/ 60}       — целых часов');
  print('169 % 60  = ${minutes % 60}      — остаток, минут');

  final double hours = minutes / 60;
  print('Длительность: ${hours.toStringAsFixed(1)} ч'); // округление вывода

  final int boxOffice = 773_000_000; // разделитель разрядов для читаемости
  print('Сборы: $boxOffice');
}
// @NUMBERS_END@

// ---------------------------------------------------------------------------
// 4. ВЫБОР БЕЗ IF: ТЕРНАРНЫЙ ОПЕРАТОР
// ---------------------------------------------------------------------------
// @CONDITIONS@
void demoConditions() {
  print('\n=== 4. Условные выражения ===\n');

  final int minutes = 169;

  // условие ? значение-если-истина : значение-если-ложь
  final String length = minutes < 90 ? 'короткий' : 'полнометражный';
  print('Фильм $length');

  // Цепочка тернарных операторов даёт три градации
  final String category = minutes < 90
      ? 'короткий'
      : minutes < 150
      ? 'обычный'
      : 'длинный';
  print('Категория: $category');

  // Логическое значение получают сравнением. Приведения числа к bool
  // в Dart НЕТ: запись if (minutes) — ошибка компиляции.
  final bool isLong = minutes > 150;
  print('Длинный: $isLong');
}
// @CONDITIONS_END@

