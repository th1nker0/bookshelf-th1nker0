// @OUTPUT@
void demoOutput() {
  print('\n=== 1. Вывод и интерполяция ===\n');

  // print добавляет перевод строки, stdout.write — нет.
  // Поэтому приглашение к вводу печатают именно через stdout.write.
  stdout.write('Напечатано без перевода строки. ');
  print('А это — с переводом.');

  final String title = 'Интерстеллар';
  final int year = 2014;

  print('Фильм: $title'); // $имя — подстановка переменной
  print('Прошло лет: ${DateTime.now().year - year}'); // ${...} — выражение
  print('В названии ${title.length} символов');
  print('-' * 30); // умножение строки — удобный разделитель
}
// @OUTPUT_END@

