// 5. КОЛЛЕКЦИИ: LIST, SET, MAP
// ---------------------------------------------------------------------------
// @COLLECTIONS@
void demoCollections() {
  print('\n=== 5. Коллекции ===\n');

  // @LIST@
  // --- List: упорядоченный список, доступ по номеру ---
  final List<String> movies = <String>[
    'Интерстеллар',
    'Начало',
    'Престиж',
    'Дюнкерк',
  ];
  print('Список: $movies');
  print('Всего: ${movies.length}, первый: ${movies.first}');
  print('Второй по счёту: ${movies[1]} — нумерация с нуля!');

  movies.insert(0, 'Помни'); // вставка в начало
  movies.add('Довод'); // добавление в конец
  movies.remove('Дюнкерк'); // удаление по значению
  print('После изменений: $movies');

  // @LIST_END@
  // @SET@
  // --- Set: множество, повторы отбрасываются сами ---
  final List<String> withDuplicates = <String>['драма', 'фантастика', 'драма'];
  final Set<String> genres = withDuplicates.toSet();
  print('Было ${withDuplicates.length}, осталось ${genres.length}: $genres');

  // Разбор строки, введённой через запятую
  const String input = 'драма, фантастика , ДРАМА';
  final Set<String> parsed = input
      .split(',') // делим по запятой
      .map((String g) => g.trim().toLowerCase()) // чистим, приводим к нижнему
      .where((String g) => g.isNotEmpty) // выбрасываем пустые
      .toSet(); // превращаем в множество
  print('Из строки «$input» получилось: $parsed');

  // @SET_END@
  // @MAP@
  // --- Map: пары «ключ — значение» ---
  final Map<String, int> minutesByMovie = <String, int>{
    'Интерстеллар': 169,
    'Начало': 148,
    'Престиж': 130,
  };
  print('Длительность «Начала»: ${minutesByMovie['Начало']}');
  print('Несуществующий ключ даёт ${minutesByMovie['Аватар']}, а не ошибку');

  minutesByMovie.forEach((String name, int value) {
    print('  $name — $value мин');
  });

  // Максимум и сумма — методом reduce, циклы не нужны
  final int longest = minutesByMovie.values.reduce(
    (int a, int b) => a > b ? a : b,
  );
  final int total = minutesByMovie.values.reduce((int a, int b) => a + b);
  print('Самый длинный: $longest мин, суммарно: $total мин');
  print('В среднем: ${(total / minutesByMovie.length).toStringAsFixed(1)} мин');

  // @MAP_END@
  // @LITERAL@
  // --- Литерал с раскрытием, условием и циклом ---
  const bool showNew = true;
  final List<String> all = <String>[
    ...movies, // раскрытие другого списка
    if (showNew) 'Оппенгеймер', // элемент по условию
    for (int i = 1; i <= 2; i++) 'Часть $i', // элементы циклом
  ];
  print('Итоговый список: $all');
  // @LITERAL_END@
}
// @COLLECTIONS_END@

